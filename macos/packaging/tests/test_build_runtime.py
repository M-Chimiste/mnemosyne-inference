MODULE_PATH = Path(__file__).resolve().parents[1] / "build_runtime.py"
SPEC = importlib.util.spec_from_file_location("mnemosyne_build_runtime", MODULE_PATH)
assert SPEC is not None and SPEC.loader is not None
build_runtime = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(build_runtime)


class LockedRequirementsTests(unittest.TestCase):
    def test_runtime_target_matches_the_app_deployment_target(self) -> None:
        with (build_runtime.PACKAGING_DIR / "Info.plist").open("rb") as stream:
            info = plistlib.load(stream)

        self.assertEqual(
            info["LSMinimumSystemVersion"],
            build_runtime.TARGET_MACOS_VERSION_TEXT,
        )

    def test_parser_keeps_exact_pins_and_markers(self) -> None:
        exported = """
        # generated by uv
        pydantic-core==2.46.4
        fastapi==0.139.2
        colorama==0.4.6 ; sys_platform == 'win32'
        """

        self.assertEqual(
            build_runtime.parse_locked_requirements(exported),
            (
                "colorama==0.4.6 ; sys_platform == 'win32'",
                "fastapi==0.139.2",
                "pydantic-core==2.46.4",
            ),
        )

    def test_parser_rejects_broad_requirement(self) -> None:
        with self.assertRaisesRegex(RuntimeError, "non-exact"):
            build_runtime.parse_locked_requirements("fastapi>=0.115,<1\n")

    def test_parser_accepts_github_requirement_pinned_to_full_commit(self) -> None:
        requirement = (
            "mflux @ git+https://github.com/filipstrand/mflux.git@"
            "97ac5e6280e8c65e48a609722229eb9d03ef2cbe"
        )

        self.assertEqual(
            build_runtime.parse_locked_requirements(requirement),
            (requirement,),
        )

    def test_parser_rejects_mutable_or_short_git_references(self) -> None:
        for requirement in (
            "mflux @ git+https://github.com/filipstrand/mflux.git@main",
            "mflux @ git+https://github.com/filipstrand/mflux.git@97ac5e62",
            "mflux @ git+ssh://github.com/filipstrand/mflux.git@"
            "97ac5e6280e8c65e48a609722229eb9d03ef2cbe",
        ):
            with self.subTest(requirement=requirement):
                with self.assertRaisesRegex(RuntimeError, "non-exact"):
                    build_runtime.parse_locked_requirements(requirement)

    def test_locked_export_is_offline_and_requires_current_lock(self) -> None:
        completed = mock.Mock(returncode=0, stdout="fastapi==0.139.2\n", stderr="")
        with (
            mock.patch.object(build_runtime, "uv_driver", return_value="/bin/uv"),
            mock.patch.object(build_runtime.subprocess, "run", return_value=completed) as run,
        ):
            self.assertEqual(
                build_runtime.locked_requirements(), ("fastapi==0.139.2",)
            )

        command = run.call_args.args[0]
        self.assertIn("--locked", command)
        self.assertIn("--offline", command)
        self.assertIn("--no-cache", command)
        self.assertIn("--no-dev", command)
        self.assertIn("--no-emit-project", command)

    def test_materialize_vcs_wheels_builds_commit_keyed_file_requirement(self) -> None:
        requirement = (
            "mflux @ git+https://github.com/filipstrand/mflux.git@"
            "97ac5e6280e8c65e48a609722229eb9d03ef2cbe"
        )
        with tempfile.TemporaryDirectory() as temporary:
            wheel_root = Path(temporary) / "wheels"
            bindings: list[dict[str, str]] = []

            def fake_run(command: list[str]) -> None:
                if len(command) > 1 and command[1] == "build":
                    output = Path(command[command.index("--out-dir") + 1])
                    output.mkdir(parents=True, exist_ok=True)
                    with zipfile.ZipFile(
                        output / "mflux-0.18.0-py3-none-any.whl",
                        "w",
                    ) as archive:
                        archive.writestr(
                            "mflux-0.18.0.dist-info/METADATA",
                            "Metadata-Version: 2.3\nName: mflux\nVersion: 0.18.0\n",
                        )

            with (
                mock.patch.object(build_runtime, "VCS_WHEEL_DIR", wheel_root),
                mock.patch.object(build_runtime, "uv_driver", return_value="/bin/uv"),
                mock.patch.object(build_runtime, "run", side_effect=fake_run) as run,
                mock.patch.object(
                    build_runtime.subprocess,
                    "run",
                    return_value=mock.Mock(
                        stdout="97ac5e6280e8c65e48a609722229eb9d03ef2cbe\n"
                    ),
                ),
            ):
                materialized = build_runtime.materialize_vcs_wheels(
                    (requirement,),
                    bindings=bindings,
                )
                sidecar = next(wheel_root.rglob(build_runtime.VCS_WHEEL_PROVENANCE_NAME))
                recorded = json.loads(sidecar.read_text(encoding="utf-8"))
                wheel = next(wheel_root.rglob("*.whl"))
                wheel.write_bytes(wheel.read_bytes() + b"tampered")
                match = build_runtime.EXACT_GITHUB_REQUIREMENT.fullmatch(requirement)
                assert match is not None
                self.assertIsNone(build_runtime._cached_vcs_wheel(wheel.parent, match))

        self.assertEqual(len(materialized), 1)
        self.assertTrue(materialized[0].startswith("mflux @ file://"))
        self.assertIn("97ac5e6280e8c65e48a609722229eb9d03ef2cbe", materialized[0])
        self.assertEqual(run.call_count, 5)
        self.assertEqual(bindings, [{key: value for key, value in recorded.items() if key != "schema_version"}])
        self.assertEqual(recorded["source_url"], "https://github.com/filipstrand/mflux.git")
        self.assertRegex(recorded["wheel_sha256"], r"^[0-9a-f]{64}$")

    def test_vcs_wheel_cache_rejects_symlinked_project_directory(self) -> None:
        requirement = (
            "mflux @ git+https://github.com/filipstrand/mflux.git@"
            "97ac5e6280e8c65e48a609722229eb9d03ef2cbe"
        )
        match = build_runtime.EXACT_GITHUB_REQUIREMENT.fullmatch(requirement)
        assert match is not None
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            wheel_root = root / "wheels"
            wheel_root.mkdir()
            outside = root / "outside"
            outside.mkdir()
            (wheel_root / "mflux").symlink_to(outside, target_is_directory=True)
            wheel_dir = wheel_root / "mflux" / match.group("commit")

            with (
                mock.patch.object(build_runtime, "VCS_WHEEL_DIR", wheel_root),
                self.assertRaisesRegex(RuntimeError, "cache directory is unsafe"),
            ):
                build_runtime._build_vcs_wheel(wheel_dir, match)

            self.assertEqual(list(outside.iterdir()), [])

    def test_registry_wheel_binding_selects_declared_macos_target(self) -> None:
        lock = '''
version = 1
revision = 3

[[package]]
name = "mlx"
version = "0.31.2"
source = { registry = "https://pypi.org/simple" }
wheels = [
    { url = "https://files.pythonhosted.org/mlx-0.31.2-cp312-cp312-macosx_14_0_arm64.whl", hash = "sha256:aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa", size = 1 },
    { url = "https://files.pythonhosted.org/mlx-0.31.2-cp312-cp312-macosx_15_0_arm64.whl", hash = "sha256:bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb", size = 1 },
    { url = "https://files.pythonhosted.org/mlx-0.31.2-cp312-cp312-macosx_26_0_arm64.whl", hash = "sha256:cccccccccccccccccccccccccccccccccccccccccccccccccccccccccccccccc", size = 1 },
]
'''
        with tempfile.TemporaryDirectory() as temporary:
            lock_path = Path(temporary) / "uv.lock"
            lock_path.write_text(lock, encoding="utf-8")
            bindings: list[dict[str, str]] = []
            rendered = build_runtime.bind_locked_registry_wheels(
                ("mlx==0.31.2 ; sys_platform == 'darwin'",),
                lock_path,
                bindings=bindings,
            )

        self.assertEqual(len(bindings), 1)
        self.assertIn("macosx_15_0_arm64.whl#sha256=" + "b" * 64, rendered[0])
        self.assertTrue(rendered[0].endswith(" ; sys_platform == 'darwin'"))
        self.assertEqual(
            bindings[0]["wheel_filename"],
            "mlx-0.31.2-cp312-cp312-macosx_15_0_arm64.whl",
        )


    def test_export_provenance_binds_both_locks_and_required_layers(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            payload = root / "payload.txt"
            payload.write_text("trusted", encoding="utf-8")
            graph = {
                "layers": {
                    "framework-mnemosyne-base": {"distributions": [], "identity": {}},
                    "framework-mnemosyne-image": {"distributions": [], "identity": {}},
                },
                "runtime_identity": dict(build_runtime.EXPECTED_PYTHON_IDENTITY),
            }
            with mock.patch.object(build_runtime, "_runtime_graph", return_value=graph):
                provenance = build_runtime.write_export_provenance(
                    root,
                    vcs_bindings={
                        "framework-mnemosyne-base": [],
                        "framework-mnemosyne-image": [],
                    },
                )
                build_runtime.validate_export(root)
                value = json.loads(provenance.read_text(encoding="utf-8"))

            self.assertEqual(value["schema_version"], 1)
            self.assertEqual(
                value["service_lock_sha256"],
                build_runtime.lock_digest(),
            )
            self.assertEqual(
                value["image_worker_lock_sha256"],
                build_runtime.lock_digest(build_runtime.IMAGE_WORKER_LOCK),
            )
            self.assertEqual(provenance.stat().st_mode & 0o777, 0o644)
            self.assertTrue((root / build_runtime.EXPORT_MANIFEST_NAME).is_file())

            value["service_lock_sha256"] = "0" * 64
            provenance.write_text(json.dumps(value), encoding="utf-8")
            with (
                mock.patch.object(build_runtime, "_runtime_graph", return_value=graph),
                self.assertRaisesRegex(RuntimeError, "provenance is stale"),
            ):
                build_runtime.validate_export(root)


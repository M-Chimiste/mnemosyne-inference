    def test_mach_o_deployment_target_is_enforced_for_every_binary(self) -> None:
        def mach_o(minimum: tuple[int, int, int]) -> bytes:
            encoded = minimum[0] << 16 | minimum[1] << 8 | minimum[2]
            command = struct.pack(
                "<IIIIII",
                build_runtime._LC_BUILD_VERSION,
                24,
                build_runtime._PLATFORM_MACOS,
                encoded,
                encoded,
                0,
            )
            header = struct.pack(
                "<IIIIIIII",
                0xFEEDFACF,
                0x0100000C,
                0,
                6,
                1,
                len(command),
                0,
                0,
            )
            return header + command

        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            supported = root / "supported.dylib"
            supported.write_bytes(mach_o((15, 0, 0)))
            build_runtime.validate_mach_o_deployment_targets(root)
            self.assertEqual(
                build_runtime.mach_o_minimum_versions(supported),
                ((15, 0, 0),),
            )

            (root / "host-newer.dylib").write_bytes(mach_o((26, 0, 0)))
            with self.assertRaisesRegex(RuntimeError, "newer than 15.0"):
                build_runtime.validate_mach_o_deployment_targets(root)


